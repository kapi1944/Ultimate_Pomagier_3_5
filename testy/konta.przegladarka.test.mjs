import { spawn } from 'node:child_process'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import test from 'node:test'
const wymagaj = createRequire(import.meta.url)
const { chromium } = wymagaj(process.env.POMAGIER_PLAYWRIGHT || 'playwright')
const adres = process.env.POMAGIER_ADRES || 'http://127.0.0.1:5193'

test('Windows Chrome: kartoteka, import, edycja zbiorcza, eksport, kopia, podgląd i rozdzielczości', { timeout: 120000 }, async () => {
  const serwer = process.env.POMAGIER_ADRES ? null : spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--mode', 'demonstracyjny', '--host', '127.0.0.1', '--port', '5193', '--strictPort'], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  if (serwer) await new Promise((rozwiaz, odrzuc) => {
    const limit = setTimeout(() => odrzuc(new Error('Serwer testowy nie wystartował')), 30000)
    serwer.stdout.on('data', (dane) => { if (dane.toString().includes('Local:')) { clearTimeout(limit); rozwiaz() } })
    serwer.on('error', odrzuc)
    serwer.on('exit', (kod) => { if (kod) odrzuc(new Error('Serwer testowy zakończył się: ' + kod)) })
  })
  const przegladarka = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const kontekst = await przegladarka.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Europe/Warsaw' })
    const strona = await kontekst.newPage(), bledy = []
    strona.on('pageerror', (blad) => bledy.push(blad.message))
    await strona.goto(adres)
    assert.equal(await strona.locator('input[type="password"]').count(), 1)
    assert.equal(await strona.locator('input[type="radio"]').count(), 0)
    await strona.getByLabel('Login lub adres e-mail').fill('test@example.test')
    await strona.getByLabel('Hasło', { exact: true }).fill('tylko-test-bez-wysylania')
    await strona.getByRole('button', { name: 'Pokaż hasło', exact: true }).click()
    assert.equal(await strona.getByLabel('Hasło', { exact: true }).getAttribute('type'), 'text')
    await strona.getByRole('button', { name: 'Zaloguj', exact: true }).click()
    await strona.getByRole('alert').waitFor()
    assert.equal(await strona.getByLabel('Hasło', { exact: true }).inputValue(), '')
    await strona.getByRole('button', { name: 'Otwórz demonstrację Architekta', exact: true }).click()
    await strona.locator('.naglowek-aplikacji').waitFor()
    await strona.locator('[aria-controls="menu-glowne"]').click()
    await strona.getByRole('button', { name: /Przypnij Menu/ }).click()
    await strona.getByRole('button', { name: 'ADMINISTRACJA', exact: true }).click()
    await strona.getByRole('button', { name: 'Użytkownicy', exact: true }).click()
    const panel = strona.getByRole('region', { name: 'Zbiorcze zarządzanie użytkownikami' })
    await panel.waitFor()
    const tabela = panel.getByRole('region', { name: 'Tabela kont', exact: true })
    assert.equal(await tabela.locator('tbody tr').count(), 17)
    await panel.getByLabel('Szukaj', { exact: true }).fill('Izabela')
    assert.equal(await tabela.locator('tbody tr').count(), 2)
    await panel.getByLabel('Szukaj', { exact: true }).fill('')
    await panel.getByLabel('Zaznacz Paweł Kwieciński', { exact: true }).check()
    await panel.getByLabel('Zaznacz Tomasz Czekaj', { exact: true }).check()
    await panel.getByLabel('Organizacja zbiorcza', { exact: true }).selectOption('IIST')
    await panel.getByRole('button', { name: 'Podgląd zmian zbiorczych', exact: true }).click()
    await panel.getByRole('button', { name: 'Akceptuj wszystkie poprawne zmiany', exact: true }).click()
    await panel.getByRole('button', { name: 'Zapisz zaakceptowane zmiany', exact: true }).click()
    await panel.getByRole('status').filter({ hasText: 'Zapisano 2 kont' }).waitFor()
    assert.equal(await tabela.locator('tbody tr').filter({ hasText: 'Paweł Kwieciński' }).locator('td').nth(5).innerText(), 'IIST')
    const przed = await strona.evaluate(() => localStorage.getItem('ultimatePomagier.uzytkownicy.v1'))
    const csv = 'ID;Login;Telefon;Nieznana kolumna\nadministrator-kacper-madej;k.madej;;test\npracownik-pawel-kwiecinski;p.kwiecinski;123;test'
    await panel.getByLabel('Plik użytkowników', { exact: true }).setInputFiles({ name: 'test-konta.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
    await panel.getByRole('heading', { name: 'Krok 2 — Rozpoznaj kolumny', exact: true }).waitFor()
    await panel.getByRole('button', { name: 'Porównaj dane', exact: true }).click()
    await panel.getByRole('heading', { name: /Wiersz 3:.*BŁĄD/ }).waitFor()
    assert.equal(await strona.evaluate(() => localStorage.getItem('ultimatePomagier.uzytkownicy.v1')), przed)
    await panel.getByRole('button', { name: 'Anuluj import', exact: true }).click()
    assert.equal(await strona.evaluate(() => localStorage.getItem('ultimatePomagier.uzytkownicy.v1')), przed)
    await panel.getByLabel('Plik użytkowników', { exact: true }).setInputFiles({ name: 'test-konta.csv', mimeType: 'text/csv', buffer: Buffer.from('ID;Login\nadministrator-kacper-madej;k.madej') })
    await panel.getByRole('button', { name: 'Porównaj dane', exact: true }).click()
    await panel.getByRole('button', { name: 'Akceptuj konto', exact: true }).click()
    await panel.getByRole('button', { name: 'Zapisz zaakceptowane zmiany', exact: true }).click()
    await panel.getByRole('status').filter({ hasText: 'Zapisano 1 kont' }).waitFor()
    assert.equal(await tabela.locator('tbody tr').filter({ hasText: 'Kacper Madej' }).locator('td').nth(3).innerText(), 'k.madej')
    const [pobranie] = await Promise.all([strona.waitForEvent('download'), panel.getByRole('button', { name: 'Eksport XLSX', exact: true }).click()])
    assert.equal(pobranie.suggestedFilename(), 'uzytkownicy.xlsx')
    await panel.getByLabel('Wyszukaj użytkownika do podglądu', { exact: true }).fill('Paweł')
    await panel.getByLabel('Konto do podglądu', { exact: true }).selectOption('pracownik-pawel-kwiecinski')
    const sesjaPrzed = await strona.evaluate(() => localStorage.getItem('ultimatePomagier.sesjaUzytkownika.v1'))
    await panel.getByRole('button', { name: 'Uruchom podgląd', exact: true }).click()
    await strona.getByRole('dialog', { name: 'Tryb podglądu użytkownika' }).waitFor()
    assert.equal(await strona.evaluate(() => localStorage.getItem('ultimatePomagier.sesjaUzytkownika.v1')), sesjaPrzed)
    await strona.keyboard.press('Escape')
    assert.equal(await strona.getByRole('dialog').count(), 0)
    await strona.getByRole('button', { name: 'Profil', exact: true }).click()
    await strona.getByRole('button', { name: 'Edytuj profil', exact: true }).click()
    for (const nazwa of ['Dane osobowe', 'Kontakt', 'Organizacja i rola', 'Uprawnienia', 'Uwierzytelnianie', 'Powiązania z kartotekami', 'Historia i aktywność']) assert.equal(await strona.getByRole('heading', { name: nazwa, exact: true }).count(), 1)
    await strona.getByRole('button', { name: 'Anuluj', exact: true }).click()
    await strona.getByRole('button', { name: 'Użytkownicy', exact: true }).click()
    for (const rozmiar of [{ width: 1920, height: 1080 }, { width: 1280, height: 720 }, { width: 800, height: 600 }]) {
      await strona.setViewportSize(rozmiar)
      assert.ok(await strona.locator('.uzytkownicy').evaluate((element) => element.scrollWidth <= element.clientWidth + 2), `Szerokość widoku ${rozmiar.width}`)
      const obszar = strona.getByRole('region', { name: 'Tabela kont', exact: true })
      await obszar.focus(); await strona.keyboard.press('ArrowRight')
      if (process.env.POMAGIER_ZRZUT) await strona.screenshot({ path: `${process.env.POMAGIER_ZRZUT}-${rozmiar.width}.png`, fullPage: false })
    }
    await strona.locator('html').evaluate((element) => { element.style.fontSize = '125%' })
    assert.ok(await strona.locator('.uzytkownicy').evaluate((element) => element.scrollWidth <= element.clientWidth + 2))
    await strona.locator('html').evaluate((element) => { element.style.fontSize = '' })
    await strona.getByText('Kopie zapasowe i odzyskiwanie', { exact: true }).click()
    await strona.getByRole('button', { name: 'Podgląd stanu sprzed ostatniej operacji', exact: true }).click()
    await strona.getByRole('checkbox', { name: 'Akceptuję przywrócenie pokazanych danych i unieważnienie sesji', exact: true }).check()
    await strona.getByRole('button', { name: 'Przywróć kopię', exact: true }).click()
    await strona.getByRole('button', { name: 'Otwórz demonstrację Architekta', exact: true }).click()
    await strona.getByRole('button', { name: 'Użytkownicy', exact: true }).click()
    const poPrzywroceniu = strona.getByRole('region', { name: 'Tabela kont', exact: true })
    assert.equal(await poPrzywroceniu.locator('tbody tr').filter({ hasText: 'Kacper Madej' }).locator('td').nth(3).innerText(), 'kacper.madej')
    const dlugieImie = Array(8).fill('SyntetyczneDługieImię').join(' ')
    const dlugieNazwisko = Array(8).fill('SyntetyczneDługieNazwisko').join('-')
    await panel.getByLabel('Plik użytkowników', { exact: true }).setInputFiles({ name: 'dlugie-konto.csv', mimeType: 'text/csv', buffer: Buffer.from('Login;Imię;Nazwisko\na.pelc;' + dlugieImie + ';' + dlugieNazwisko) })
    await panel.getByRole('button', { name: 'Porównaj dane', exact: true }).click()
    await panel.getByRole('button', { name: 'Akceptuj konto', exact: true }).click()
    await panel.getByRole('button', { name: 'Zapisz zaakceptowane zmiany', exact: true }).click()
    assert.equal(await poPrzywroceniu.locator('tbody tr').filter({ hasText: dlugieNazwisko }).count(), 1)
    assert.ok(await strona.locator('.uzytkownicy').evaluate((element) => element.scrollWidth <= element.clientWidth + 2))
    assert.deepEqual(bledy, [])
  } catch (blad) {
    if (process.env.POMAGIER_ZRZUT) { const strony = przegladarka.contexts().flatMap((kontekst) => kontekst.pages()); if (strony[0]) await strony[0].screenshot({ path: process.env.POMAGIER_ZRZUT + '-blad.png' }) }
    throw blad
  } finally { await przegladarka.close(); serwer?.kill() }
})
