import assert from 'node:assert/strict'
import { aktywneWidoki, odczytaj } from './inwentaryzacjaV4.mjs'
import { pobierzPreferencjePowloki, zapiszPreferencjePowloki, pobierzPreferencjeDrzewaMenu, zapiszPreferencjeDrzewaMenu, pobierzKluczDrzewaMenu, kluczPrzypieciaMenu, kluczWysuwaniaZKrawedzi, pobierzDostepneSkroty, domyslneSkroty } from '../src/aplikacja/menu/preferencjeMenu.ts'
import { pobierzKontekstNawigacji } from '../src/aplikacja/menu/pozycjeMenu.ts'
import { ustawObslugeNiezapisanegoDokumentu, czyDokumentMaNiezapisaneZmiany, zapiszDokumentPrzedWyjsciem } from '../src/moduly/dokumenty/wspolne/strzeznikNiezapisanegoDokumentu.ts'

const magazyn = new Map()
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (klucz) => magazyn.get(klucz) ?? null, setItem: (klucz, wartosc) => magazyn.set(klucz, wartosc) }, configurable: true })
Object.defineProperty(globalThis, 'window', { value: new EventTarget(), configurable: true })
assert.deepEqual(pobierzPreferencjePowloki('a'), { przypiete: false, wysuwanie: true, widocznyDock: null, skroty: domyslneSkroty })
magazyn.set(kluczPrzypieciaMenu, 'true')
magazyn.set(kluczWysuwaniaZKrawedzi, 'false')
const staryRekord = { tryb: 'pelne', rozwiniete: { dokumenty: true }, dodatkowe: 'zachowaj' }
magazyn.set(pobierzKluczDrzewaMenu('a'), JSON.stringify(staryRekord))
assert.equal(pobierzPreferencjePowloki('a').przypiete, true)
assert.equal(pobierzPreferencjePowloki('a').wysuwanie, false)
assert.equal(magazyn.get(pobierzKluczDrzewaMenu('a')), JSON.stringify(staryRekord), 'Odczyt nie migruje destrukcyjnie')
assert.equal(zapiszPreferencjePowloki('a', { przypiete: false, widocznyDock: false, skroty: [] }), true)
assert.equal(pobierzPreferencjePowloki('b').przypiete, true, 'Inny użytkownik zachowuje własny fallback')
assert.deepEqual(pobierzPreferencjeDrzewaMenu('a'), { tryb: 'pelne', rozwiniete: { dokumenty: true } })
assert.equal(zapiszPreferencjeDrzewaMenu('a', { tryb: 'zwijane', rozwiniete: {} }), true)
assert.deepEqual(pobierzPreferencjePowloki('a').skroty, [], 'Zapis drzewa nie przywraca odpiętych skrótów')
assert.equal(pobierzPreferencjePowloki('a').widocznyDock, false)
assert.equal(JSON.parse(magazyn.get(pobierzKluczDrzewaMenu('a'))).dodatkowe, 'zachowaj')
assert.equal(magazyn.get(kluczPrzypieciaMenu), 'true', 'Nie nadpisuje globalnych preferencji legacy')
magazyn.set(pobierzKluczDrzewaMenu('c'), JSON.stringify({ powloka: { skroty: ['pulpit', 'nieistniejacy', 'pulpit', null, 'profil_uzytkownika'], widocznyDock: 'błąd' } }))
assert.deepEqual(pobierzPreferencjePowloki('c').skroty, ['pulpit', 'profil_uzytkownika'])
assert.equal(pobierzPreferencjePowloki('c').widocznyDock, null)
magazyn.set(pobierzKluczDrzewaMenu('d'), '{uszkodzony')
assert.deepEqual(pobierzPreferencjePowloki('d').skroty, domyslneSkroty)
assert.equal(zapiszPreferencjePowloki('d', { przypiete: true }), false)
assert.equal(magazyn.get(pobierzKluczDrzewaMenu('d')), '{uszkodzony')
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: () => null, setItem: () => { throw new Error('Brak miejsca') } }, configurable: true })
assert.equal(zapiszPreferencjePowloki('a', { widocznyDock: true }), false)

const widoki = aktywneWidoki()
assert.deepEqual(pobierzDostepneSkroty().map((pozycja) => pozycja.widok).sort(), widoki)
for (const widok of widoki) assert.ok(pobierzKontekstNawigacji(widok).length > 0, `Brak kontekstu: ${widok}`)
const wyrejestruj = ustawObslugeNiezapisanegoDokumentu({ czySaNiezapisaneZmiany: () => true, zapiszPrzedWyjsciem: () => false })
assert.equal(czyDokumentMaNiezapisaneZmiany(), true)
assert.equal(zapiszDokumentPrzedWyjsciem(), false, 'Nieudany zapis blokuje wyjście')
wyrejestruj()
const uklad = odczytaj('src/aplikacja/layout/UkladAplikacji.tsx')
assert.match(uklad, /<DockAplikacji[^>]+ustawWidok=\{ustawWidok\}/)
assert.match(uklad, /<MenuBoczne[^>]+ustawAktywnyWidok=\{ustawWidok\}/)
assert.match(uklad, /if \(!zapiszDokumentPrzedWyjsciem\(\)\) return/)
assert.doesNotMatch(odczytaj('src/aplikacja/layout/DockAplikacji.tsx'), /pushState|ustawAktywnyWidok|location\./)
assert.match(odczytaj('src/aplikacja/layout/powlokaV4.css'), /@media print[\s\S]*\.dock-aplikacji[\s\S]*display: none !important/)
console.log('V4-02: preferencje per użytkownik, legacy, pełna lista skrótów, kontekst oraz centralny guard — OK.')
