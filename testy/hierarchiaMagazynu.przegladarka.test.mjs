    const prostokat = await element.boundingBox()
    await strona.mouse.move(prostokat.x + 12, prostokat.y + 12)
    await strona.mouse.down()
    await strona.mouse.move(prostokat.x + 80, prostokat.y + 35, { steps: 5 })
