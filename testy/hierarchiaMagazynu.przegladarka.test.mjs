test('magazyn: brakująca lokalizacja, konflikt zapisu i zachowanie błędnej edycji', { timeout: 90000 }, async () => {
  const przegladarka = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const strona = await przegladarka.newPage({ viewport: { width: 1440, height: 1000 } })
    await zaloguj(strona)
    await strona.evaluate(({ klucz, zapis }) => localStorage.setItem(klucz, zapis), { klucz, zapis: staryPlan })
    await strona.reload()
    await strona.getByRole('button', { name: 'Edytuj plan', exact: true }).click()
    const przypisania = strona.getByRole('region', { name: 'Przypisywanie produktów' })
    await przypisania.getByRole('button', { name: 'Utwórz brakującą lokalizację', exact: true }).click()
    const kreator = strona.getByRole('form', { name: 'Kreator lokalizacji' })
    await kreator.getByLabel('Nazwa nowej lokalizacji').fill('Nowa strefa')
    await kreator.getByLabel('Liczba półek', { exact: true }).fill('0')
    await kreator.getByRole('button', { name: 'Utwórz strukturę', exact: true }).click()
    assert.equal(await przypisania.getByRole('combobox', { name: 'Lokalizacja docelowa', exact: true }).count(), 1, await przypisania.ariaSnapshot())
    const wybrana = await przypisania.getByRole('combobox', { name: 'Lokalizacja docelowa', exact: true }).inputValue()
    assert.ok(wybrana)
    const szczegoly = strona.getByRole('complementary', { name: 'Szczegóły lokalizacji' })
    await szczegoly.getByLabel('Kod', { exact: true }).fill('MAG')
    await szczegoly.getByRole('button', { name: 'Zastosuj edycję lokalizacji' }).click()
    await strona.getByRole('alert').filter({ hasText: 'unikalny' }).waitFor()
    assert.equal(await szczegoly.getByLabel('Kod', { exact: true }).inputValue(), 'MAG')
    await strona.getByRole('button', { name: 'Zapisz konfigurację', exact: true }).click()
    await strona.getByRole('alert').filter({ hasText: 'Najpierw zastosuj' }).waitFor()
    assert.equal(await strona.evaluate((klucz) => localStorage.getItem(klucz), klucz), staryPlan)
    await szczegoly.getByLabel('Kod', { exact: true }).fill('NOWA')
    await szczegoly.getByRole('button', { name: 'Zastosuj edycję lokalizacji' }).click()
    await strona.evaluate((klucz) => { const dane = JSON.parse(localStorage.getItem(klucz)); dane.lokalizacje[0].nazwa = 'Zmiana w drugim oknie'; localStorage.setItem(klucz, JSON.stringify(dane)) }, klucz)
    await strona.getByRole('button', { name: 'Zapisz konfigurację', exact: true }).click()
    await strona.getByRole('alert').filter({ hasText: 'innym oknie' }).waitFor()
    assert.equal(await szczegoly.getByLabel('Kod', { exact: true }).inputValue(), 'NOWA')
    assert.equal((await odczytaj(strona)).lokalizacje[0].nazwa, 'Zmiana w drugim oknie')
    assert.equal(await przypisania.getByRole('combobox', { name: 'Lokalizacja docelowa', exact: true }).inputValue(), wybrana)
  } finally { await przegladarka.close() }
})

test('magazyn: masowe półki, duplikacja, kolejność i opcjonalna geometria', { timeout: 90000 }, async () => {
  const przegladarka = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const strona = await przegladarka.newPage({ viewport: { width: 1440, height: 1000 } })
    await zaloguj(strona)
    await strona.evaluate(({ klucz, zapis }) => localStorage.setItem(klucz, zapis), { klucz, zapis: staryPlan })
    await strona.reload()
    await strona.getByRole('button', { name: 'Edytuj plan', exact: true }).click()
    await strona.getByRole('button', { name: 'Dodaj lokalizację w tym planie', exact: true }).click()
    const kreator = strona.getByRole('form', { name: 'Kreator lokalizacji' })
    await kreator.getByLabel('Nazwa nowej lokalizacji').fill('Pudełka')
    await kreator.getByLabel('Liczba półek', { exact: true }).fill('2')
    await kreator.getByRole('button', { name: 'Utwórz strukturę', exact: true }).click()
    const drzewo = strona.getByRole('navigation', { name: 'Drzewo lokalizacji' })
    const szczegoly = strona.getByRole('complementary', { name: 'Szczegóły lokalizacji' })
    await szczegoly.getByLabel('Liczba dodawanych półek', { exact: true }).fill('2')
    await szczegoly.getByRole('button', { name: 'Dodaj półki jednocześnie', exact: true }).click()
    assert.equal(await drzewo.locator('button[title^="PUDELKA/POLKA-"]').count(), 4)
    await drzewo.locator('button[title="PUDELKA/POLKA-2"]').click()
    await szczegoly.getByRole('button', { name: 'Przenieś wyżej', exact: true }).click()
    assert.equal((await drzewo.locator('button[title^="PUDELKA/POLKA-"]').evaluateAll((elementy) => elementy.map((element) => element.title)))[0], 'PUDELKA/POLKA-2')
    await szczegoly.getByRole('switch', { name: 'Pokaż na mapie', exact: true }).check()
    assert.equal(await strona.locator('.mapa-magazynu__miejsce strong').textContent(), 'POLKA-2')
    await drzewo.locator('button[title="PUDELKA"]').click()
    await szczegoly.getByRole('button', { name: 'Duplikuj strukturę', exact: true }).click()
    assert.equal(await drzewo.locator('button[title^="PUDELKA-KOPIA-1/POLKA-"]').count(), 4)
    await strona.getByRole('button', { name: 'Zapisz konfigurację', exact: true }).click()
    await strona.getByRole('button', { name: 'Edytuj plan', exact: true }).waitFor()
    const zapis = await odczytaj(strona)
    assert.equal(zapis.lokalizacje.length, 13)
    assert.equal(new Set(zapis.lokalizacje.map((lokalizacja) => lokalizacja.id)).size, 13)
    assert.equal(zapis.lokalizacje.find((lokalizacja) => lokalizacja.pelnyKod === 'PUDELKA/POLKA-2').kolejnosc, 0)
    assert.ok(zapis.lokalizacje.find((lokalizacja) => lokalizacja.pelnyKod === 'PUDELKA/POLKA-2').polozenieNaMapie)
    assert.ok(zapis.lokalizacje.filter((lokalizacja) => lokalizacja.pelnyKod.startsWith('PUDELKA-KOPIA-1')).every((lokalizacja) => !lokalizacja.polozenieNaMapie))
    assert.equal(zapis.daneMagazynowe.stanyWLokalizacjach.length, 0)
    await strona.reload()
    await drzewo.locator('button[title="PUDELKA/POLKA-2"]').click()
    assert.equal(await strona.locator('.mapa-magazynu__miejsce strong').textContent(), 'POLKA-2')
    assert.deepEqual(await odczytaj(strona), zapis)
  } finally { await przegladarka.close() }
})
