import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import test from 'node:test'
import { mkdir } from 'node:fs/promises'

const wymagaj = createRequire(import.meta.url)
const { chromium } = wymagaj(process.env.POMAGIER_PLAYWRIGHT || 'playwright')
const adres = process.env.POMAGIER_ADRES || 'http://127.0.0.1:5173'
const klucz = 'ultimatePomagier.zakupy.lokalizacje.v1'
const staryPlan = JSON.stringify({ wersja: 1, lokalizacje: [
  { id: 'mag', kod: 'MAG', nazwa: 'Magazyn', czyAktywna: true, polozenieNaMapie: { x: 10, y: 10, szerokosc: 50, wysokosc: 50 } },
  { id: 'lewa', kod: 'LEWA', nazwa: 'Lewa strona', czyAktywna: true, nadrzednaLokalizacjaId: 'mag' },
  { id: 'prawa', kod: 'PRAWA', nazwa: 'Prawa strona', czyAktywna: true, nadrzednaLokalizacjaId: 'mag' },
] })

async function zaloguj(strona) {
  strona.setDefaultTimeout(10000)
  await strona.goto(adres + '/zakupy/magazyn/mapa')
  await strona.getByRole('button', { name: 'Otwórz demonstrację Architekta', exact: true }).click()
  await strona.locator('.mapa-magazynu').waitFor()
}
async function odczytaj(strona) { return strona.evaluate((klucz) => JSON.parse(localStorage.getItem(klucz)), klucz) }

