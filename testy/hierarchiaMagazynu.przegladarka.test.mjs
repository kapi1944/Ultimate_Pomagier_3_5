    await kreator.getByRole('switch', { name: 'Umieść nową lokalizację na mapie' }).check()
    await kreator.getByRole('button', { name: 'Utwórz strukturę', exact: true }).click()
    const drzewo = strona.getByRole('navigation', { name: 'Drzewo lokalizacji' })
    assert.equal(await drzewo.locator('button[title^="MAG/LEWA/KARTONY/POLKA-"]').count(), 5)
    await strona.getByLabel('Szukaj lokalizacji', { exact: true }).fill('arton')
    assert.equal(await drzewo.locator('button[title="MAG/LEWA/KARTONY"]').count(), 1)
    assert.equal(await drzewo.locator('button[title="MAG/PRAWA"]').count(), 0)
    assert.equal(await strona.locator('.mapa-magazynu__element--trafienie').count(), 1)
    await strona.getByLabel('Szukaj lokalizacji', { exact: true }).fill('')
    const przypisania = strona.getByRole('region', { name: 'Przypisywanie produktów' })
    await przypisania.locator('summary').click()
    await przypisania.getByLabel('Nazwa produktu', { exact: true }).fill('Papier A4')
    await przypisania.getByLabel('Jednostka miary', { exact: true }).fill('ryza')
    await przypisania.getByRole('button', { name: 'Dodaj produkt do zmian', exact: true }).click()
    await przypisania.getByLabel('Szukaj: Lokalizacja docelowa', { exact: true }).fill('polka-1')
    assert.equal(await przypisania.getByRole('combobox', { name: 'Lokalizacja docelowa', exact: true }).count(), 1, await przypisania.ariaSnapshot())
    await przypisania.getByRole('combobox', { name: 'Lokalizacja docelowa', exact: true }).selectOption({ label: 'MAG/LEWA/KARTONY/POLKA-1 — Półka 1' })
    await przypisania.getByLabel('Ilość (ryza)', { exact: true }).fill('12')
    await przypisania.getByRole('button', { name: 'Dodaj przypisanie do zmian', exact: true }).click()
    await przypisania.getByLabel('Szukaj: Lokalizacja docelowa', { exact: true }).fill('polka-2')
    await przypisania.getByRole('combobox', { name: 'Lokalizacja docelowa', exact: true }).selectOption({ label: 'MAG/LEWA/KARTONY/POLKA-2 — Półka 2' })
    await przypisania.getByLabel('Ilość (ryza)', { exact: true }).fill('18')
    await przypisania.getByRole('button', { name: 'Dodaj przypisanie do zmian', exact: true }).click()
    await przypisania.getByRole('switch', { name: /Przesuń istniejący zapas/ }).check()
    await przypisania.getByRole('combobox', { name: 'Lokalizacja źródłowa', exact: true }).selectOption({ label: 'MAG/LEWA/KARTONY/POLKA-1 — Półka 1' })
    await przypisania.getByLabel('Ilość (ryza)', { exact: true }).fill('5')
    await przypisania.getByRole('button', { name: 'Dodaj przypisanie do zmian', exact: true }).click()
    await drzewo.locator('button[title="MAG/LEWA/KARTONY"]').click()
    const szczegoly = strona.getByRole('complementary', { name: 'Szczegóły lokalizacji' })
    assert.match(await szczegoly.innerText(), /7 ryza/)
    assert.match(await szczegoly.innerText(), /23 ryza/)
    await szczegoly.getByRole('combobox', { name: 'Lokalizacja nadrzędna', exact: true }).selectOption('prawa')
    await szczegoly.getByRole('button', { name: 'Zastosuj edycję lokalizacji' }).click()
    await szczegoly.getByRole('heading', { name: 'MAG/PRAWA/KARTONY — Kartony', exact: true }).waitFor()
    await strona.getByRole('switch', { name: 'Siatka 5%', exact: true }).check()
    const element = strona.locator('.mapa-magazynu__miejsce').filter({ has: strona.locator('strong', { hasText: /^KARTONY$/ }) })
