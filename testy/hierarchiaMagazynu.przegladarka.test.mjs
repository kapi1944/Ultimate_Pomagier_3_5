    const bledy = []
    strona.on('pageerror', (blad) => bledy.push(blad.message))
    await zaloguj(strona)
    await strona.evaluate(({ klucz, zapis }) => localStorage.setItem(klucz, zapis), { klucz, zapis: staryPlan })
    await strona.reload()
    await strona.getByRole('button', { name: 'Edytuj plan', exact: true }).click()
